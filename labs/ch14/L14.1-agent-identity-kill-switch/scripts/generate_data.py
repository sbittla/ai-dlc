def anchors(records: list[dict]) -> list[dict]:
    """The head of the chain at the end of every hour that had records (what the anchor store holds)."""
    out: list[dict] = []
    for rec in records:
        head = {"seq": rec["seq"], "hash": rec["hash"], "hour": rec["at"][:13] + ":00Z"}
        if out and out[-1]["hour"] == head["hour"]:
            out[-1] = head
        else:
            out.append(head)
    return out


def tampered(records: list[dict]) -> dict[str, list[dict]]:
    from relay.audit import record_hash
    edit = [dict(r) for r in records]
    edit[199] = {**edit[199], "detail": {**edit[199]["detail"], "rows": 3}}
    deleted = [dict(r) for r in records[:299]] + [dict(r) for r in records[300:]]
    truncated = [dict(r) for r in records[:-120]]
    rewritten = [dict(r) for r in records]
    rewritten[199] = {**rewritten[199], "detail": {**rewritten[199]["detail"], "rows": 3}}
    prev = rewritten[198]["hash"]
    for i in range(199, len(rewritten)):
        rewritten[i]["prev"] = prev
        rewritten[i]["hash"] = record_hash(rewritten[i])
        prev = rewritten[i]["hash"]
    return {"T1-edited-record": edit, "T2-deleted-record": deleted, "T3-truncated-tail": truncated,
            "T4-edited-and-rehashed": rewritten}


