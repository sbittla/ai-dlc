def write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes((json.dumps(data, indent=2, sort_keys=True) + "\n").encode("utf-8"))


def copy_bytes(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_bytes(src.read_bytes().replace(b"\r\n", b"\n"))


def write(out: Path) -> None:
    tickets = (L71 / "tickets.jsonl").read_bytes().replace(b"\r\n", b"\n")
    expected = json.loads((L71 / "manifest.json").read_text(encoding="utf-8"))["files"]["tickets.jsonl"]
    if hashlib.sha256(tickets).hexdigest() != expected:
        raise SystemExit("Lab 7.1's tickets.jsonl does not match its manifest")
    (out / "source").mkdir(parents=True, exist_ok=True)
    (out / "source" / "tickets.jsonl").write_bytes(tickets)
    with open(L171 / "data" / "traffic" / "week-2027-02-01.csv", newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    col = rows[0].index("post_triage_job")
    lines = ["minute,post_triage_job"] + [f"{r[0]},{r[col]}" for r in rows[1:]]
    (out / "source" / "tickets-per-minute.csv").write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    relay = L171 / "relay-repo" / "src" / "relay"
    target = out / "relay-4.28.0" / "src" / "relay"
    copy_bytes(relay / "__init__.py", target / "__init__.py")
    for p in sorted((relay / "routing").glob("*.py")):
        copy_bytes(p, target / "routing" / p.name)
    write_json(out / "models.json", MODELS)
    write_json(out / "configs.json", CONFIGS)
    write_json(out / "abuse.json", ABUSE)
    write_json(out / "incident.json", INCIDENT)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(LAB / "data"))
    args = ap.parse_args()
    write(Path(args.out))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
