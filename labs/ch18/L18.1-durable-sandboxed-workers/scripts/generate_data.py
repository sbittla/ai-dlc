def iso(t: datetime) -> str:
    return t.strftime("%Y-%m-%dT%H:%M:%SZ")


def pilot() -> tuple[list[dict], list[dict]]:
    rng = random.Random(PILOT["seed"])
    start = datetime.fromisoformat(PILOT["start"].replace("Z", "+00:00"))
    tickets, deliveries = [], []
    n = 0
    for day in range(PILOT["days"]):
        date = start + timedelta(days=day)
        mean = PILOT["tickets_per_day"]["weekday" if date.weekday() < 5 else "weekend"]
        count = max(0, round(rng.gauss(mean, math.sqrt(mean))))
        for _ in range(count):
            n += 1
            opened = date + timedelta(seconds=rng.randrange(7 * 3600, 20 * 3600))
            eligible = rng.random() < PILOT["true_duplicate_share"]
            tickets.append({"ticket_id": f"BT-{3000 + n}", "opened_at": iso(opened), "customer": f"ws-{rng.randrange(100, 400)}",
                            "charge_id": f"ch_{5000 + n:05d}", "amount_usd": rng.choice(PILOT["amounts_usd"]),
                            "eligible": eligible})
    tickets.sort(key=lambda t: (t["opened_at"], t["ticket_id"]))
    msg = 0
    for t in tickets:
        opened = datetime.fromisoformat(t["opened_at"].replace("Z", "+00:00"))
        chains = [("first", opened)]
        if rng.random() < PILOT["webhook_duplicate_rate"]:
            lo, hi = PILOT["webhook_duplicate_delay_s"]
            chains.append(("webhook_duplicate", opened + timedelta(seconds=rng.randint(lo, hi))))
        for cause, at in chains:
            msg += 1
            message_id = f"m-{msg:05d}"
            delivered, first = at, True
            while True:
                seconds = round(rng.lognormvariate(math.log(PILOT["processing_s"]["median"]),
                                                   PILOT["processing_s"]["sigma"]), 1)
                deliveries.append({"message_id": message_id, "ticket_id": t["ticket_id"], "charge_id": t["charge_id"],
                                   "delivered_at": iso(delivered), "processing_s": seconds,
                                   "cause": cause if first else "visibility_timeout"})
                if seconds <= PILOT["visibility_timeout_s"]:
                    break
                delivered += timedelta(seconds=PILOT["visibility_timeout_s"])
                first = False
    deliveries.sort(key=lambda d: (d["delivered_at"], d["message_id"], d["cause"]))
    return tickets, deliveries


def jsonl(rows: list[dict]) -> str:
    return "".join(json.dumps(r, sort_keys=True) + "\n" for r in rows)


def files() -> dict[str, str]:
    tickets, deliveries = pilot()
    out = {"pilot/tickets.jsonl": jsonl(tickets), "pilot/deliveries.jsonl": jsonl(deliveries),
           "escapes.json": json.dumps(ESCAPES, indent=2, sort_keys=True) + "\n",
           "drills.json": json.dumps(DRILLS, indent=2, sort_keys=True) + "\n"}
    manifest = {"GENERATED": NOTE, "pilot": PILOT,
                "files": {k: hashlib.sha256(v.encode("utf-8")).hexdigest() for k, v in sorted(out.items())}}
    out["manifest.json"] = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(LAB / "data"))
    args = ap.parse_args()
    root = Path(args.out)
    for rel, text in files().items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))  # LF on every platform
    print(f"wrote {len(files())} files under {root}")


if __name__ == "__main__":
    main()
