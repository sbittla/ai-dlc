def files() -> dict[str, str]:
    out = {name: json.dumps(obj, indent=2, sort_keys=True) + "\n" for name, obj in
           (("serving.json", SERVING), ("workload.json", WORKLOAD), ("relay-volume.json", VOLUME),
            ("model-manifest.json", MANIFEST))}
    out["manifest.json"] = json.dumps({"GENERATED": NOTE, "files": {k: hashlib.sha256(v.encode()).hexdigest()
                                                                    for k, v in sorted(out.items())}},
                                      indent=2, sort_keys=True) + "\n"
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(LAB / "data"))
    root = Path(ap.parse_args().out)
    for rel, text in files().items():
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_bytes(text.encode("utf-8"))
    print(f"wrote {len(files())} files under {root}")


if __name__ == "__main__":
    main()
