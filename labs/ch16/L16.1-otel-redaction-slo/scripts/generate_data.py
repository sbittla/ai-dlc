def journal():
    """Agent runs of the spec-to-PR helper, written by Relay's own RunStore (Chapter 10)."""
    store = RunStore()
    rng = random.Random(SEED + 3)
    t0 = datetime(2027, 2, 1, 9, 0, tzinfo=timezone.utc)
    plan = (["finished"] * 31 + ["handed_back"] * 3 + ["budget:usd", "budget:steps", "budget:usd"] +
            ["unknown_outcome", "revoked", "finished"])
    tools = ["read_task", "read_file", "search_code", "edit_file", "run_tests", "run_prcheck", "open_pull_request"]
    for n, kind in enumerate(plan):
        at = t0 + timedelta(hours=7 * n)
        stamp = lambda s: (at + timedelta(seconds=s)).strftime("%Y-%m-%dT%H:%M:%SZ")  # noqa: E731
        run_id, _ = store.start_run(f"lab16-{n:03d}", f"RLY-{2300 + n}", "routed", "spec-to-pr-helper",
                                    rng.choice(["priya.n", "sam.o"]), stamp(0))
        steps = rng.randint(4, 9)
        sec = 0
        for s in range(steps):
            sec += rng.randint(2, 40)
            tool = tools[min(s, len(tools) - 2)]
            seq, _ = store.begin_step(run_id, f"idem-{n}-{s}" if tool in ("edit_file", "run_tests") else None,
                                      "spec-to-pr-helper", tool, f"{rng.getrandbits(256):064x}", stamp(sec))
            store.finish_step(run_id, seq, "ok", {"value": "ok"})
        sec += rng.randint(2, 30)
        if kind == "unknown_outcome":
            store.note_step(run_id, "spec-to-pr-helper", "open_pull_request", f"{rng.getrandbits(256):064x}",
                            "refused", {"code": "unknown_outcome", "detail": "the step may already have happened"},
                            stamp(sec))
            store.set_status(run_id, "handed_back", "unknown_outcome", stamp(sec + 1))
        elif kind.startswith("budget:"):
            store.set_status(run_id, "stopped", kind, stamp(sec))
        elif kind == "revoked":
            store.set_status(run_id, "revoked", "revoked:disabled", stamp(sec))
        elif kind == "handed_back":
            store.set_status(run_id, "handed_back", "repeated_failure:run_tests", stamp(sec))
        else:
            store.set_status(run_id, "finished", None, stamp(sec))
    runs = [store.run(f"run-lab16-{n:03d}") for n in range(len(plan))]
    return {"label": LABEL, "runs": runs, "steps": {r["run_id"]: store.steps(r["run_id"]) for r in runs}}


def triage_quality(rng: random.Random):
    """Daily online-evaluation counts for SLO-TRIAGE-QUALITY: confirmations, and how many were kept unchanged."""
    rows = []
    for d in range(DAYS):
        day = START + timedelta(days=d)
        n = poisson(rng, 70 if day.weekday() < 5 else 25)
        rate = 0.65 if 15 <= d <= 21 else 0.86  # configured: a drop for seven days (19-25 January)
        kept = sum(1 for _ in range(n) if rng.random() < rate)
        rows.append((day.strftime("%Y-%m-%d"), kept, n))
    return rows


def pilot(rng: random.Random):
    """January's escalation pilot in two workspaces: every fired step, its due and fired times, and each email."""
    t0 = datetime(2027, 1, 4, tzinfo=timezone.utc)
    targets = {"pilot-a": list(range(101, 121)), "pilot-b": list(range(201, 216))}
    steps = []
    for d in range(28):
        day = t0 + timedelta(days=d)
        for ws, users in targets.items():
            for _ in range(poisson(rng, 55 if day.weekday() < 5 else 15)):
                due = day + timedelta(seconds=rng.randint(6 * 3600, 22 * 3600))
                priority = rng.choices(["P1", "P2", "P3", "P4"], [2, 4, 3, 1])[0]
                steps.append({"workspace": ws, "priority": priority, "target": rng.choice(users), "due_at": due})
    # Configured: the platform outage of Thursday 21 January, 10:00-10:50, 23 P1 steps for pilot-a's on-call user.
    outage = datetime(2027, 1, 21, 10, 0, tzinfo=timezone.utc)
    for i in range(23):
        steps.append({"workspace": "pilot-a", "priority": "P1", "target": 104,
                      "due_at": outage + timedelta(minutes=2 * i, seconds=17)})
    # Configured: a bulk import on Tuesday 12 January makes a P3 rule fire 64 steps for one target in 40 minutes.
    for i in range(64):
        steps.append({"workspace": "pilot-b", "priority": "P3", "target": 207,
                      "due_at": datetime(2027, 1, 12, 13, 0, tzinfo=timezone.utc) + timedelta(seconds=37 * i)})
    stall = (datetime(2027, 1, 19, 2, 0, tzinfo=timezone.utc), datetime(2027, 1, 19, 4, 30, tzinfo=timezone.utc))
    for i in range(70):  # configured: overnight work in pilot-b while the evaluator was stalled
        steps.append({"workspace": "pilot-b", "priority": rng.choice(["P2", "P3"]), "target": rng.choice(range(201, 216)),
                      "due_at": stall[0] + timedelta(minutes=2 * i + 1)})
    steps.sort(key=lambda s: (s["due_at"], s["workspace"], s["target"]))
    out, sent = [], {}
    for s in steps:
        due = s["due_at"]
        delay = rng.uniform(0.2, 1.8)
        if stall[0] <= due < stall[1]:  # configured: the evaluator stalled 02:00-04:30 on Tuesday 19 January
            delay = (stall[1] - due).total_seconds() + rng.uniform(0.2, 1.8)
        fired = due + timedelta(seconds=delay)
        hist = [t for t in sent.get(s["target"], []) if t > fired - timedelta(hours=1)]
        outcome = "held" if len(hist) >= 20 else "emailed"
        if outcome == "emailed":
            hist.append(fired)
        sent[s["target"]] = hist
        ack = None
        if s["priority"] == "P1":
            ack = fired + timedelta(seconds=rng.randint(40, 420) if rng.random() < 0.9 else rng.randint(700, 2400))
        out.append({"workspace": s["workspace"], "priority": s["priority"], "target": s["target"],
                    "due_at": due.strftime("%Y-%m-%dT%H:%M:%SZ"), "fired_at": fired.strftime("%Y-%m-%dT%H:%M:%S.%fZ"),
                    "email": outcome, "webhook": "delivered",
                    "acknowledged_at": ack.strftime("%Y-%m-%dT%H:%M:%SZ") if ack else None})
    # The outage's P1s were acknowledged together by the on-call user, who was already working the outage.
    for row in out:
        if row["target"] == 104 and row["due_at"].startswith("2027-01-21T10:"):
            row["acknowledged_at"] = "2027-01-21T10:03:05Z" if row["due_at"] < "2027-01-21T10:03" else \
                (datetime.strptime(row["fired_at"], "%Y-%m-%dT%H:%M:%S.%fZ") + timedelta(seconds=55)).strftime(
                    "%Y-%m-%dT%H:%M:%SZ")
    return out


def write(out: Path) -> None:
    rng = random.Random(SEED)
    (out / "traffic").mkdir(parents=True, exist_ok=True)
    rows, manifest = traffic(rng)
    with open(out / "traffic" / "api-minutes.csv", "w", encoding="utf-8", newline="\n") as fh:
        fh.write(f"# {LABEL}\nminute,total,errors,slow\n")
        fh.writelines(f"{m},{t},{e},{s}\n" for m, t, e, s in rows)
    dump(out / "traffic" / "manifest.json", {"label": LABEL, "start": START.strftime("%Y-%m-%dT%H:%MZ"), "days": DAYS,
                                             "rollback_at": "2027-02-02T15:31Z", "events": manifest})
    q = triage_quality(random.Random(SEED + 1))
    with open(out / "traffic" / "triage-quality-days.csv", "w", encoding="utf-8", newline="\n") as fh:
        fh.write(f"# {LABEL}\nday,kept,confirmed\n")
        fh.writelines(f"{d},{k},{n}\n" for d, k, n in q)
    (out / "redaction").mkdir(exist_ok=True)
    jsonl(out / "redaction" / "probes.jsonl", probes())
    (out / "requests").mkdir(exist_ok=True)
    jsonl(out / "requests" / "script.jsonl", requests())
    (out / "agents").mkdir(exist_ok=True)
    dump(out / "agents" / "journal.json", journal())
    (out / "pilot").mkdir(exist_ok=True)
    jsonl(out / "pilot" / "escalations-2027-01.jsonl", pilot(random.Random(SEED + 2)))
    dump(out / "pilot" / "manifest.json", {"label": LABEL, "workspaces": ["pilot-a", "pilot-b"],
                                           "from": "2027-01-04", "to": "2027-01-31",
                                           "configured": ["outage 2027-01-21 10:00-10:50, 23 P1 steps for user 104",
                                                          "bulk import 2027-01-12 13:00, 64 P3 steps for user 207",
                                                          "evaluator stalled 2027-01-19 02:00-04:30"]})


def dump(path: Path, doc) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=True) + "\n")


def jsonl(path: Path, rows) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.writelines(json.dumps(r, sort_keys=True, ensure_ascii=True) + "\n" for r in rows)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(LAB / "data"))
    write(Path(ap.parse_args().out))


if __name__ == "__main__":
    main()
