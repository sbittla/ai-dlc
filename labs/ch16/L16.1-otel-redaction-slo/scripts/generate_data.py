def traffic(rng: random.Random):
    rows, manifest = [], []
    spans = {}
    for eid, title, start, minutes, err, slow, kind in EVENTS:
        s = start.replace(tzinfo=timezone.utc)
        idx = int((s - START).total_seconds() // 60)
        spans[eid] = (idx, idx + minutes - 1, err, slow)
    for m in range(DAYS * 1440):
        t = START + timedelta(minutes=m)
        hour = t.hour + t.minute / 60
        day_factor = 0.4 if t.weekday() >= 5 else 1.0
        base = 40 + 160 * max(0.0, math.sin(math.pi * (hour - 6) / 14)) * day_factor
        total = max(1, poisson(rng, base))
        err_p, slow_p = 0.0002, 0.003
        for eid, (a, b, err, slow) in spans.items():
            if a <= m <= b:
                err_p, slow_p = max(err_p, err), max(slow_p, slow)
        errors = min(total, poisson(rng, total * err_p))
        slow = min(total - errors, poisson(rng, (total - errors) * slow_p))
        rows.append((t.strftime("%Y-%m-%dT%H:%MZ"), total, errors, slow))
    for eid, title, start, minutes, err, slow, kind in EVENTS:
        s = start.replace(tzinfo=timezone.utc)
        manifest.append({"id": eid, "title": title, "kind": kind, "start": s.strftime("%Y-%m-%dT%H:%MZ"),
                         "end": (s + timedelta(minutes=minutes - 1)).strftime("%Y-%m-%dT%H:%MZ"),
                         "error_ratio": err, "slow_ratio": slow})
    return rows, manifest


