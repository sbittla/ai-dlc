        attacking = ATTACK[0] <= t < ATTACK[1]
        ramp = min(1.0, (t - ATTACK[0]).total_seconds() / 240) if attacking else 0.0
        ok = poisson(rng, 95)
        fail = poisson(rng, 6)
        att_fail = att_ok = 0
        if attacking:
            n = poisson(rng, 720 * ramp)
            att_ok = sum(1 for _ in range(n) if rng.random() < 0.0011)
            att_fail = n - att_ok
        api = poisson(rng, 3200)
        signin_db = (ok + fail + att_fail + att_ok) * 38.0  # ms of database time per sign-in attempt
        notify_db = api * 0.04
        other_db = api * 1.9
