# --- helpers -------------------------------------------------------------------------------------------------

def sha(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def write_json(path: Path, obj) -> None:
    write_text(path, json.dumps(obj, indent=2, ensure_ascii=False) + "\n")


def roots_map(pack: dict, pack_dir: Path) -> dict:
    out = {"pack": pack_dir}
    for name, where in pack.get("roots", {}).items():
        out[name] = REPO / where
    return out


def resolve(ref: str, roots: dict) -> Path:
    root, _, rel = ref.partition(":")
    return roots[root] / rel


def finalize(pack: dict, pack_dir: Path, files: dict) -> None:
    """Write the pack's own files, then record every item's and source's SHA-256 and write pack.json."""
    for rel, content in files.items():
        if isinstance(content, (dict, list)):
            write_json(pack_dir / rel, content)
        else:
            write_text(pack_dir / rel, content)
    roots = roots_map(pack, pack_dir)
    for item in pack["items"]:
        p = resolve(item["file"], roots)
        if p.is_file() and item.get("sha256", "") == "":
            item["sha256"] = sha(p)
        for s in item.get("sources", []):
            q = resolve(s["ref"], roots)
            if q.is_file() and s.get("sha256", "") == "":
                s["sha256"] = sha(q)
    write_json(pack_dir / "pack.json", pack)


def item(iid, requirement, kind, file, label, owner, sources, **extra) -> dict:
    d = {"id": iid, "requirement": requirement, "kind": kind, "file": file, "label": label, "owner": owner,
         "sha256": "", "sources": [{"ref": s, "sha256": ""} for s in sources]}
    d.update(extra)
    return d


def wilson(k: int, n: int) -> list[float]:
    from capstone.kinds import wilson as w
    lo, hi = w(k, n)
    return [round(lo, 4), round(hi, 4)]


def run_lab(lab: Path, args: list[str]) -> str:
    env = dict(os.environ, LAB_TARGET="solution", PYTHONPATH=str(lab / "solution"), PYTHONIOENCODING="utf-8",
               PYTHONDONTWRITEBYTECODE="1")
    res = subprocess.run([sys.executable, *args], cwd=lab / "solution", env=env, capture_output=True, text=True,
                         encoding="utf-8", check=True)
    return res.stdout.replace("\r\n", "\n")


