def build_releases(out: Path) -> None:
    sys.path.insert(0, str(RELAY / "tools"))
    import sbom  # noqa: E402  (Relay 4.25.0's own generator)

    out.mkdir(parents=True, exist_ok=True)
    key = b"lab-13.1-stand-in-for-the-sigstore-ca-and-log"
    trust = {"generated": GENERATED,
             "note": "STAND-IN for Sigstore's trust root. Signatures here are HMAC-SHA256 with this published "
                     "key, so anyone can forge them; real keyless signing uses a short-lived certificate from "
                     "Fulcio and an entry in the Rekor transparency log.",
             "hmac_key": key.decode(),
             "expected_issuer": "https://token.actions.githubusercontent.com",
             "expected_identity": "https://github.com/relay-example/relay/.github/workflows/release.yml"
                                  "@refs/tags/v{version}"}
    (out / "trust-root.json").write_text(dump(trust), encoding="utf-8", newline="\n")
    digest = "sha256:" + standin("image:relay:4.25.0")
    good_sbom = sbom.build_sbom(RELAY, "4.25.0", digest, AS_OF)
    good_ai = sbom.build_aibom(RELAY, "4.25.0", digest, AS_OF)
    ident = trust["expected_identity"].format(version="4.25.0")

    def bundle(name, sbom_doc, ai_doc, identity=ident, tlog=True, tamper=None):
        d = out / name
        d.mkdir(exist_ok=True)
        s_text, a_text = dump(sbom_doc), dump(ai_doc)
        statement = {"_type": "https://in-toto.io/Statement/v1",
                     "subject": [{"name": "relay", "digest": {"sha256": digest[7:]}}],
                     "predicateType": "https://relay.example/release/v1",
                     "predicate": {"version": "4.25.0", "sbom_sha256": hashlib.sha256(s_text.encode()).hexdigest(),
                                   "aibom_sha256": hashlib.sha256(a_text.encode()).hexdigest()}}
        cert = {"issuer": trust["expected_issuer"], "identity": identity,
                "not_before": "2027-01-28T14:02:10Z", "not_after": "2027-01-28T14:12:10Z"}
        payload = json.dumps({"certificate": cert, "statement": statement}, sort_keys=True).encode()
        b = {"mediaType": "application/vnd.relay.lab.simulated-bundle+json", "generated": GENERATED,
             "statement": statement, "certificate": cert,
             "signature": hmac.new(key, payload, hashlib.sha256).hexdigest(),
             "tlog": {"log_index": 18_204_331, "integrated_time": "2027-01-28T14:02:14Z"} if tlog else None}
        if tamper == "sbom":
            sbom_doc = json.loads(s_text)
            sbom_doc["components"][2]["version"] = "23.0.1"
            s_text = dump(sbom_doc)
        (d / "artifact.json").write_text(dump({"image": "relay", "digest": digest, "generated": GENERATED}), encoding="utf-8", newline="\n")
        (d / "sbom.cdx.json").write_text(s_text, encoding="utf-8", newline="\n")
        (d / "aibom.cdx.json").write_text(a_text, encoding="utf-8", newline="\n")
        (d / "bundle.json").write_text(dump(b), encoding="utf-8", newline="\n")

    bundle("RC-1", good_sbom, good_ai)
    bundle("RC-2", good_sbom, good_ai, tamper="sbom")
    bundle("RC-3", good_sbom, good_ai,
           identity="https://github.com/relay-example/relay/.github/workflows/release.yml"
                    "@refs/heads/agent/rly-2207-verifier")
    ai4 = json.loads(dump(good_ai))
