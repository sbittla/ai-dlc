def standin(text: str) -> str:
    return hashlib.sha256(("lab-stand-in:" + text).encode()).hexdigest()


def fingerprint(rule: str, path: str, line: str) -> str:
    return hashlib.sha256(f"{rule}|{path}|{line.strip()}".encode()).hexdigest()[:16]


def dump(obj) -> str:
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


