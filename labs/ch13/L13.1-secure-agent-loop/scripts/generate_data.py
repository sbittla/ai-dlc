def build(out: Path) -> None:
    rng = random.Random(SEED)
    policy = json.loads((RELAY / "supply-chain" / "mirror.json").read_text(encoding="utf-8"))
    out.mkdir(parents=True, exist_ok=True)

    # 1. changes and truth
    items = []
    for cat, variants in DETECTION.items():
        for k, (variant, found) in enumerate(variants):
            items.append(("seeded", cat, variant, found, k))
    clean = [("clean", t, lines, fa) for t, lines, fa in CLEAN * 7][:53] + [("clean", t, l, fa)
                                                                           for t, l, fa in FALSE_ALARMS]
    order = list(range(len(items) + len(clean)))
    rng.shuffle(order)
    changes, truth, sem, gl, tv = [], {}, [], [], []
    clean_alarm_ids = {}
    for pos, idx in enumerate(order, 1):
        cid = f"AC{pos:03d}"
        if idx < len(items):
            _, cat, variant, found, k = items[idx]
            files, req, line = seeded(cat, variant, k, rng)
            truth[cid] = {"seeded": True, "category": cat, "cwe": CWE[cat], "variant": variant}
            task = f"Agent task: {cat.replace('-', ' ')} area, variant {k + 1}"
            if files:
                text = files[0]["content"].splitlines()[line - 1]
                path = files[0]["path"]
                if "semgrep" in found:
                    rule, sev = SEMGREP_RULE[cat]
                    sem.append((cid, rule, sev, path, line, text, f"{CWE[cat]}: {rule}"))
                if "gitleaks" in found:
                    gl.append((cid, "relay-token", 9.0, path, line, text, "Relay token in source"))
                if cat == "iac-misconfiguration":
                    rid, msg, sev = IAC_RULE[variant]
                    tv.append((cid, rid, sev, path, line, text, msg))
            if cat == "vulnerable-dependency":
                adv = next(a for a in ADVISORIES if f"{a['package']}=={a['affected']}" == variant)
                tv.append((cid, adv["id"], adv["severity"], "deploy/requirements.txt", 1, req[0],
                           f"{variant}: {adv['summary']} (fixed in {adv['fixed']})"))
        else:
            _, t, lines, fa = clean[idx - len(items)]
            path = f"src/relay/service/{ROUTES[pos % len(ROUTES)]}_helpers.py"
            files, req = [pyfile(path, ['"""Agent change."""', "", "import os", ""] + lines)], None
            truth[cid] = {"seeded": False, "category": "clean", "cwe": None, "variant": t}
            task = f"Agent task: {t.lower()}"
            if fa:
                scanner, rule, sev, ln = fa
                text = files[0]["content"].splitlines()[ln + 3]
                rec = (cid, rule, sev, path, ln + 4, text, f"{rule} (false alarm in this fixture)")
                (sem if scanner == "semgrep" else gl).append(rec)
                clean_alarm_ids[FALSE_ALARMS.index((t, lines, fa))] = (cid, rule, path, text)
        ch = {"id": cid, "task": task, "files": files}
        if req:
            ch["requirements"] = {"file": "deploy/requirements.txt", "added_lines": req}
        changes.append(ch)

    (out / "changes").mkdir(exist_ok=True)
    (out / "changes" / "changes.jsonl").write_text("".join(json.dumps(c, sort_keys=True) + "\n" for c in changes),
                                                   encoding="utf-8", newline="\n")
    (out / "changes" / "truth.json").write_text(dump({"generated": GENERATED, "changes": truth}), encoding="utf-8",
                                                newline="\n")

    # 2. SARIF
    (out / "scans").mkdir(exist_ok=True)
    for name, recs, version in (("semgrep", sem, "1.x (simulated)"), ("gitleaks", gl, "8.x (simulated)"),
                                ("trivy", tv, "0.x (simulated)")):
        results = []
        for cid, rule, sev, path, line, text, msg in sorted(recs):
            results.append({"ruleId": rule, "level": "error" if sev >= 7.0 else "warning",
                            "message": {"text": msg},
                            "locations": [{"physicalLocation": {"artifactLocation": {"uri": f"{cid}/{path}"},
                                                                "region": {"startLine": line}}}],
                            "partialFingerprints": {"primaryLocationLineHash": fingerprint(rule, path, text)},
                            "properties": {"change": cid, "security-severity": f"{sev:.1f}"}})
        sarif = {"$schema": "https://json.schemastore.org/sarif-2.1.0.json", "version": "2.1.0",
                 "runs": [{"tool": {"driver": {"name": name, "version": version}},
                           "properties": {"generated": GENERATED,
                                          "note": "simulated output; which findings appear was configured"},
                           "results": results}]}
        (out / "scans" / f"{name}.sarif.json").write_text(dump(sarif), encoding="utf-8", newline="\n")

    # 3. package fixtures
    (out / "packages").mkdir(exist_ok=True)
    (out / "packages" / "mirror-index.json").write_text(dump(mirror_index(policy)), encoding="utf-8", newline="\n")
    (out / "packages" / "public-index.json").write_text(dump(public_index()), encoding="utf-8", newline="\n")
    (out / "packages" / "advisories.json").write_text(dump({"generated": GENERATED, "advisories": ADVISORIES}),
                                                      encoding="utf-8", newline="\n")

    # 4. suppressions
    seeded_sqli = next(c for c in changes if truth[c["id"]]["category"] == "sql-injection"
                       and truth[c["id"]]["variant"] == "detected")
    sq = next(s for s in sem if s[0] == seeded_sqli["id"])
    sups = []
    for n, (which, reviewer, author, created, expires, reason) in enumerate(SUPPRESSIONS, 1):
        if which == "seeded":
            cid, rule, path, text = sq[0], sq[1], sq[3], sq[5]
        else:
            cid, rule, path, text = clean_alarm_ids[which]
        sups.append({"id": f"SUP-{n:02d}", "rule": rule, "fingerprint": fingerprint(rule, path, text),
                     "for_change": cid, "reason": reason, "author": author, "reviewed_by": reviewer,
                     "created": created, "expires": expires})
    (out / "suppressions.json").write_text(dump({"generated": GENERATED, "suppressions": sups}), encoding="utf-8",
                                           newline="\n")

    # 5. fix attempts for every seeded change some scanner finds (dependency findings included)
    found_ids = [c["id"] for c in changes if truth[c["id"]]["seeded"]
                 and (truth[c["id"]]["category"] in ("hallucinated-package", "typosquat", "dependency-confusion")
                      or any(r[0] == c["id"] for r in sem + gl + tv))]
    kinds = [k for k, n in FIX_KINDS for _ in range(n)]
    assert len(kinds) == len(found_ids), (len(kinds), len(found_ids))
    rng.shuffle(kinds)
    fixes = []
    for cid, kind in zip(found_ids, kinds):
        ch = next(c for c in changes if c["id"] == cid)
        own = [f["path"] for f in ch["files"]] or ["deploy/requirements.txt"]
        fix = {"change": cid, "kind": kind, "claim": "fixed", "files_changed": list(own), "added_lines": [],
               "rescan_findings": 0, "tests_pass": True}
        if kind == "suppression-marker":
            fix["added_lines"] = ["    # nosemgrep" if truth[cid]["category"] not in ("hardcoded-secret",)
                                  else "    # gitleaks:allow"]
        elif kind == "weakened-test":
            fix["files_changed"].append("tests/test_service_escalation.py")
        elif kind == "swapped-package":
            fix["rescan_findings"] = 1
            fix["added_lines"] = ["secure-jwt-tools==0.4.0"]
        elif kind == "scanner-config":
            fix["files_changed"].append("security/gitleaks.toml")
        elif kind == "breaks-tests":
            fix["tests_pass"] = False
        elif kind == "partial":
            fix["rescan_findings"] = 1
        fixes.append(fix)
    (out / "fixes").mkdir(exist_ok=True)
    (out / "fixes" / "fixes.jsonl").write_text("".join(json.dumps(f, sort_keys=True) + "\n" for f in fixes),
                                               encoding="utf-8", newline="\n")

    # 6. releases
    build_releases(out / "releases")

    # 7. incident
    (out / "incident").mkdir(exist_ok=True)
    (out / "incident" / "timeline.json").write_text(dump(INCIDENT), encoding="utf-8", newline="\n")

    manifest = {"generated": GENERATED, "seed": SEED, "as_of": AS_OF, "changes": len(changes),
                "seeded": sum(t["seeded"] for t in truth.values()),
                "clean": sum(not t["seeded"] for t in truth.values()), "fix_attempts": len(fixes),
                "relay_version": "4.25.0"}
    (out / "manifest.json").write_text(dump(manifest), encoding="utf-8", newline="\n")


