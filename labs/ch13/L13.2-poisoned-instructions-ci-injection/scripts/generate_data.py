def tags(text: str) -> str:
    """ASCII smuggled as Unicode tag characters (U+E0000 block): invisible in most renderers."""
    return "".join(chr(0xE0000 + ord(c)) for c in text)


def vs_bytes(text: str) -> str:
    """Bytes smuggled as variation selectors after a visible character: invisible, and category Mn, not Cf."""
    return "".join(chr(0xFE00 + b) if b < 16 else chr(0xE0100 + b - 16) for b in text.encode("utf-8"))


def zero_width(text: str) -> str:
    return "​".join(text)


def insert_after(doc: str, anchor: str, new: str) -> str:
    i = doc.index(anchor) + len(anchor)
    j = doc.index("\n", i) + 1
    return doc[:j] + new + doc[j:]


