"""Generate Lab 20.2's data deterministically (synthetic; every effect below is CONFIGURED, not discovered).

    python scripts/generate_data.py            # writes data/
    python scripts/generate_data.py --out DIR  # writes elsewhere (the golden test compares the two)

The company that builds Relay has four other product teams. Their delivery data for the baseline quarter
(Q4 2026) and for the pilot (1 March to 28 May 2027) is simulated here. In the pilot, two teams (integrations,
analytics) used coding agents on randomly chosen tasks; the other two (mobile, marketplace) were the comparison
group. The configured effects are listed in CONFIG and repeated in data/README-data.md, so that nobody mistakes
them for findings: agents shorten author hours (more on small tasks than large), lengthen review hours and the
review wait, raise the failure rate slightly, and the pilot teams' shared review queue slows for both arms.
Skills and survey answers are configured with NO difference between arms except the perceived speedup question.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import io
import json
import math
import random
from datetime import date, timedelta
from pathlib import Path

LAB = Path(__file__).resolve().parent.parent
LABEL = "GENERATED by labs/ch20/L20.2-controlled-adoption-experiment/scripts/generate_data.py; synthetic and configured"
SEED = 20270226

TEAMS = {"mobile": 9, "integrations": 8, "analytics": 7, "marketplace": 10}
JUNIORS = {"mobile": 3, "integrations": 2, "analytics": 2, "marketplace": 3}
PREFIX = {"mobile": "mob", "integrations": "int", "analytics": "ana", "marketplace": "mkt"}
PILOT_TEAMS = ("integrations", "analytics")
COMPARISON_TEAMS = ("mobile", "marketplace")

BASELINE_START, BASELINE_WEEKS = date(2026, 10, 5), 13   # Monday 5 October 2026 to Friday 1 January 2027
PILOT_START, PILOT_WEEKS = date(2027, 3, 1), 13          # Monday 1 March to Friday 28 May

CONFIG = {
    "size_mix": {"S": 0.45, "M": 0.40, "L": 0.15},
    "changes_per_engineer_week": 2.0,
    "author_hours_median": {"S": 4.0, "M": 10.0, "L": 22.0},
    "review_hours_median": {"S": 1.0, "M": 2.2, "L": 4.0},
    "review_wait_hours_median": {"S": 6.0, "M": 10.0, "L": 16.0},
    "deploy_wait_hours_median": 18.0,
    "calendar_per_author_hour": 1.8,
    "sd_team": 0.12, "sd_team_period": 0.10, "sd_engineer": 0.20, "sd_author": 0.35, "sd_review": 0.35, "sd_wait": 0.60, "sd_deploy": 0.50,
    "agent_author_factor": {"S": 0.60, "M": 0.70, "L": 0.85},
    "agent_review_factor": 1.30,
    "agent_review_wait_factor": 1.35,
    "pilot_team_queue_factor": 1.10,
    "fail_rate": {"control": 0.07, "agent": 0.09, "large_extra": 0.04},
    "skill_pass": {"senior": 0.85, "junior": 0.55, "keep_answer": 0.8},
    "perceived_speedup_mean": 0.31,
    "model_usd_per_agent_change": 12.00,
}


def poisson(rng: random.Random, lam: float) -> int:
    limit, k, p = math.exp(-lam), 0, 1.0
    while True:
        p *= rng.random()
        if p <= limit:
            return k
        k += 1


def pick_size(rng: random.Random) -> str:
    x, acc = rng.random(), 0.0
    for size, share in CONFIG["size_mix"].items():
        acc += share
        if x < acc:
            return size
    return "L"


def engineers() -> list[dict]:
    people = []
    for team, n in TEAMS.items():
        for i in range(1, n + 1):
            people.append({"engineer": f"{PREFIX[team]}-{i:02d}", "team": team,
                           "level": "junior" if i <= JUNIORS[team] else "senior"})
    return people


def lognormal(rng: random.Random, median: float, sd: float, shift: float = 0.0) -> float:
    return math.exp(math.log(median) + shift + rng.gauss(0.0, sd))


def make_change(rng, cid, eng, eff, period, arm, week, start, drift=0.0):
    size = pick_size(rng)
    agent = arm == "agent"
    author = lognormal(rng, CONFIG["author_hours_median"][size], CONFIG["sd_author"], eff)
    if agent:
        author *= CONFIG["agent_author_factor"][size]
    review = lognormal(rng, CONFIG["review_hours_median"][size], CONFIG["sd_review"])
    wait = lognormal(rng, CONFIG["review_wait_hours_median"][size], CONFIG["sd_wait"], eff)
    if agent:
        review *= CONFIG["agent_review_factor"]
        wait *= CONFIG["agent_review_wait_factor"]
    if period == "pilot" and eng["team"] in PILOT_TEAMS:
        wait *= CONFIG["pilot_team_queue_factor"]
    wait *= math.exp(drift)
    deploy = lognormal(rng, CONFIG["deploy_wait_hours_median"], CONFIG["sd_deploy"], drift)
    author, review, wait, deploy = (round(v, 1) for v in (author, review, wait, deploy))
    lead = round(CONFIG["calendar_per_author_hour"] * author + wait + review + deploy, 1)
    p_fail = CONFIG["fail_rate"]["agent" if agent else "control"] + (CONFIG["fail_rate"]["large_extra"] if size == "L" else 0)
    failed = rng.random() < p_fail
    day = start + timedelta(weeks=week, days=rng.randrange(5))
    return {"change_id": cid, "period": period, "team": eng["team"], "engineer": eng["engineer"],
            "level": eng["level"], "size": size, "arm": arm, "deployed_on": day.isoformat(),
            "author_hours": f"{author:.1f}", "review_hours": f"{review:.1f}", "review_wait_hours": f"{wait:.1f}",
            "deploy_wait_hours": f"{deploy:.1f}", "lead_time_hours": f"{lead:.1f}", "failed": "1" if failed else "0"}


class BlockRandomizer:
    """Permuted blocks of four per stratum (team x size), from its own seeded generator: the assignment list."""

    def __init__(self, seed: int):
        self.rng = random.Random(seed)
        self.blocks: dict[tuple[str, str], list[str]] = {}

    def assign(self, team: str, size: str) -> str:
        block = self.blocks.setdefault((team, size), [])
        if not block:
            block.extend(["agent", "agent", "control", "control"])
            self.rng.shuffle(block)
        return block.pop()


def generate() -> dict[str, bytes]:
    rng = random.Random(SEED)
    people = engineers()
    team_eff = {t: rng.gauss(0, CONFIG["sd_team"]) for t in TEAMS}
    eng_eff = {e["engineer"]: team_eff[e["team"]] + rng.gauss(0, CONFIG["sd_engineer"]) for e in people}
    drift = {(t, p): rng.gauss(0, CONFIG["sd_team_period"]) for p in ("baseline", "pilot") for t in TEAMS}
    randomizer = BlockRandomizer(SEED + 1)
    rows, n = [], 0
    for period, start, weeks in (("baseline", BASELINE_START, BASELINE_WEEKS), ("pilot", PILOT_START, PILOT_WEEKS)):
        for week in range(weeks):
            for eng in people:
                for _ in range(poisson(rng, CONFIG["changes_per_engineer_week"])):
                    n += 1
                    if period == "baseline":
                        arm = "baseline"
                    elif eng["team"] in COMPARISON_TEAMS:
                        arm = "comparison"
                    else:
                        arm = "pending"
                    row = make_change(rng, f"C{n:05d}", eng, eng_eff[eng["engineer"]], period,
                                      "control" if arm == "pending" else arm, week, start,
                                      drift[(eng["team"], period)])
                    if arm == "pending":
                        # assign from the size, then regenerate the effects for the assigned arm from the same draws
                        assigned = randomizer.assign(eng["team"], row["size"])
                        if assigned == "agent":
                            row = rescale_for_agent(row)
                        row["arm"] = assigned
                    rows.append(row)
    rows.sort(key=lambda r: (r["deployed_on"], r["change_id"]))
    files: dict[str, bytes] = {}
    files["changes.csv"] = to_csv(rows)
    assignments = [{"change_id": r["change_id"], "team": r["team"], "size": r["size"], "arm": r["arm"]}
                   for r in rows if r["period"] == "pilot" and r["team"] in PILOT_TEAMS]
    assignments.sort(key=lambda a: a["change_id"])
    files["assignments.csv"] = to_csv(assignments)
    files["people.json"] = to_json({"label": LABEL, "pilot_teams": list(PILOT_TEAMS),
                                    "comparison_teams": list(COMPARISON_TEAMS), "engineers": people})
    files["spend.json"] = to_json(spend(rng, rows))
    files["skills.json"] = to_json(skills(rng, people))
    files["survey.json"] = to_json(survey(rng, people))
    files["README-data.md"] = readme_data()
    files["config.json"] = to_json({"label": LABEL, "seed": SEED, "configured_effects": CONFIG,
                                    "baseline": {"start": BASELINE_START.isoformat(), "weeks": BASELINE_WEEKS},
                                    "pilot": {"start": PILOT_START.isoformat(), "weeks": PILOT_WEEKS}})
    digest = hashlib.sha256(files["assignments.csv"]).hexdigest()
    files["prereg/prereg-reviewed.json"] = to_json(prereg(reviewed=True, assignment_sha256=digest))
    files["prereg/prereg-draft.json"] = to_json(prereg(reviewed=False, assignment_sha256=None))
    files["prereg/frozen.json"] = to_json({
        "label": LABEL, "id": "adoption-pilot-2027", "version": "1.0", "frozen_on": "2027-02-26",
        "held_by": "tomas.b, in the data steward's repository, outside the pilot teams' write access",
        "sha256": hashlib.sha256(files["prereg/prereg-reviewed.json"]).hexdigest()})
    return files


def rescale_for_agent(row: dict) -> dict:
    """Apply the configured agent effects to a change drawn as control (same random draws for both arms)."""
    size = row["size"]
    author = round(float(row["author_hours"]) * CONFIG["agent_author_factor"][size], 1)
    review = round(float(row["review_hours"]) * CONFIG["agent_review_factor"], 1)
    wait = round(float(row["review_wait_hours"]) * CONFIG["agent_review_wait_factor"], 1)
    deploy = float(row["deploy_wait_hours"])
    lead = round(CONFIG["calendar_per_author_hour"] * author + wait + review + deploy, 1)
    out = dict(row)
    out.update(author_hours=f"{author:.1f}", review_hours=f"{review:.1f}", review_wait_hours=f"{wait:.1f}",
               lead_time_hours=f"{lead:.1f}")
    # failure: the control draw used p_control; an agent change fails with the extra probability, from a hash of
    # the change ID so the draw is reproducible and independent of the main stream
    extra = CONFIG["fail_rate"]["agent"] - CONFIG["fail_rate"]["control"]
    u = int(hashlib.sha256(row["change_id"].encode()).hexdigest()[:8], 16) / 0xFFFFFFFF
    if row["failed"] == "0" and u < extra / (1 - CONFIG["fail_rate"]["control"]):
        out["failed"] = "1"
    return out


def spend(rng: random.Random, rows: list[dict]) -> dict:
    """The model gateway's monthly spend for each pilot team (agents only; catalog tools are seat-priced)."""
    months: dict[tuple[str, str], int] = {}
    for r in rows:
        if r["arm"] == "agent":
            key = (r["deployed_on"][:7], r["team"])
            months[key] = months.get(key, 0) + 1
    out = []
    for (month, team), n in sorted(months.items()):
        usd = n * CONFIG["model_usd_per_agent_change"] * math.exp(rng.gauss(0, 0.15))
        out.append({"month": month, "team": team, "agent_changes": n, "model_usd": round(usd, 2)})
    return {"label": LABEL, "note": "Spend recorded by the model gateway per team per calendar month; seats for "
            "catalog tools are billed separately and are the same for every team.", "months": out}


def skills(rng: random.Random, people: list[dict]) -> dict:
    """An unassisted debugging exercise at week 0 and week 13. Configured with NO difference between groups."""
    rows = []
    for e in people:
        p = CONFIG["skill_pass"][e["level"]]
        before = rng.random() < p
        after = before if rng.random() < CONFIG["skill_pass"]["keep_answer"] else (rng.random() < p)
        rows.append({"engineer": e["engineer"], "team": e["team"], "level": e["level"],
                     "before": before, "after": after})
    return {"label": LABEL, "exercise": "unassisted debugging, 45 minutes, no AI tools; equivalent exercises "
            "before (week 0) and after (week 13), marked blind by a reviewer outside the team", "results": rows}


def survey(rng: random.Random, people: list[dict]) -> dict:
    """Anonymous pulse survey, reported only as team means with n (SPACE dimensions plus psychological safety).
    Configured with no change between waves except random noise; perceived speedup is asked in pilot teams only."""
    out = []
    for team in TEAMS:
        members = [e for e in people if e["team"] == team]
        for wave in ("pre", "post"):
            n = sum(1 for _ in members if rng.random() < 0.9) or 1
            row = {"team": team, "wave": wave, "n": n,
                   "satisfaction_1_5": round(3.6 + rng.gauss(0, 0.12), 2),
                   "review_load_manageable_1_5": round(3.4 + rng.gauss(0, 0.12), 2),
                   "flow_1_5": round(3.3 + rng.gauss(0, 0.12), 2),
                   "psychological_safety_1_7": round(5.1 + rng.gauss(0, 0.15), 2)}
            if wave == "post" and team in PILOT_TEAMS:
                row["perceived_speedup_on_agent_tasks"] = round(CONFIG["perceived_speedup_mean"] + rng.gauss(0, 0.02), 3)
            out.append(row)
    return {"label": LABEL, "note": "Anonymous; reported only as team means with n, never per person. Psychological "
            "safety uses a seven-item team scale with a 1-7 response scale; the other items are single questions scored 1-5.",
            "teams": out}


