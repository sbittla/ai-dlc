def dump(path: Path, obj: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"generated": GENERATED, **obj}, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
                    encoding="utf-8", newline="\n")


def main(out: Path) -> None:
    classes = []
    for cid, effect, channel, technique, encoding, target in CLASSES:
        harm, stride, owasp, agentic, atlas, claimed, variants = EFFECTS[effect]
        classes.append({
            "id": cid, "effect": effect, "channel": channel, "technique": technique, "encoding": encoding,
            "harm": harm, "stride": stride, "owasp_llm": owasp, "owasp_agentic": agentic, "atlas": atlas,
            "target": target, "claimed": claimed, "variants": variants,
            "payload": f"[[INJECTION technique={technique} effect={effect} encoding={encoding}]]",
        })
    dump(out / "classes.json", {"catalogue": CATALOGUE_VERSION, "classes": classes})
    dump(out / "controls.json", {"controls": CONTROLS})
    dump(out / "gate-policy.json", GATE_POLICY)
    dump(out / "mappings.json", {
        "stride_extension": "STRIDE per trust boundary, labelled with OWASP LLM Top 10 2025, OWASP Agentic AI "
                            "threats and MITRE ATLAS (confirm every ID before print; ATLAS may have more specific "
                            "techniques than AML.T0051 for some classes).",
        "effects": {e: {"harm": v[0], "stride": v[1], "owasp_llm": v[2], "owasp_agentic": v[3], "atlas": v[4]}
                    for e, v in EFFECTS.items()},
        "trust_boundaries": ["prompt (instructions)", "context (tickets, documents, tool results)", "tools",
                             "memory", "outputs (rendered text, messages, network)"],
    })
    dump(out / "incident" / "timeline.json", INCIDENT)


