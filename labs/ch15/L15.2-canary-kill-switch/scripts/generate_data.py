"""Generate Lab 15.2's scenarios deterministically, and refresh vendor/ from Lab 15.1's Relay 4.29.0.

    python scripts/generate_data.py            # writes data/ and refreshes vendor/
    python scripts/generate_data.py --out DIR  # writes data elsewhere (the reproducibility test uses this)

Every scenario is SYNTHETIC and CONFIGURED here: traffic rates, error and latency probabilities, the platform
incident in R4, the one-minute spike in R6, and the quality of each triage cohort in A1 and A0. The per-minute
counts and per-ticket outcomes are drawn from these parameters by `canary/traffic.py`, seeded by scenario, minute
and version, so every run gives the same numbers on every platform. The 15-minute manual rollback used for the
all-at-once comparison is an assumption, stated in the scenario file.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

LAB = Path(__file__).resolve().parent.parent
L151 = LAB.parent / "L15.1-hardened-pipeline" / "relay-repo"
LABEL = "GENERATED by labs/ch15/L15.2-canary-kill-switch/scripts/generate_data.py; synthetic and configured"

BASE = {"stable": {"error_p": 0.0004, "slow_p": 0.004}, "canary": {"error_p": 0.0004, "slow_p": 0.004}}

TRAFFIC = [
    {"id": "R1", "title": "A healthy release", "rate_per_minute": 1200, **BASE},
    {"id": "R2", "title": "The canary returns server errors on 3% of requests", "rate_per_minute": 1200,
     "stable": BASE["stable"], "canary": {"error_p": 0.03, "slow_p": 0.004}},
    {"id": "R3", "title": "The canary answers 25% of requests in over 250 ms", "rate_per_minute": 1200,
     "stable": BASE["stable"], "canary": {"error_p": 0.0004, "slow_p": 0.25}},
    {"id": "R4", "title": "A database incident hurts both versions from minute 20 to minute 34",
     "rate_per_minute": 1200, **BASE,
     "incident": {"from": 20, "to": 34, "versions": ["stable", "canary"], "error_p": 0.03}},
    {"id": "R5", "title": "A quiet hour: 30 requests a minute", "rate_per_minute": 30, **BASE},
    {"id": "R6", "title": "One bad minute on the canary (minute 7), then healthy", "rate_per_minute": 1200, **BASE,
     "incident": {"from": 7, "to": 7, "versions": ["canary"], "error_p": 0.2}},
]

AI = [
    {"id": "A1", "title": "triage_routing_c at 25% with a prompt that passed offline and does worse online",
     "feature": "triage_routing_c", "rollout_percent": 25, "workspaces": 400, "tickets_per_hour": 100,
     "hours": 8, "bad_p": {"feature": 0.26, "control": 0.14}, "confirm_mean_minutes": 30, "check_every_minutes": 5},
    {"id": "A0", "title": "The same rollout with no real difference (the null case)",
     "feature": "triage_routing_c", "rollout_percent": 25, "workspaces": 400, "tickets_per_hour": 100,
     "hours": 8, "bad_p": {"feature": 0.14, "control": 0.14}, "confirm_mean_minutes": 30, "check_every_minutes": 5,
     "reseeds": 40},
]


def write(out: Path, rel: str, obj) -> None:
    path = out / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes((json.dumps(obj, indent=2, sort_keys=True) + "\n").encode("utf-8"))


def vendor() -> None:
    """Copy what the lab runs from Lab 15.1's Relay 4.29.0, with LF line endings."""
    pairs = [(L151 / "src" / "relay" / "__init__.py", LAB / "vendor" / "relay" / "__init__.py")]
    for name in ("__init__.py", "flags.py", "judged.py"):
        pairs.append((L151 / "src" / "relay" / "release" / name, LAB / "vendor" / "relay" / "release" / name))
    for src, dst in ((L151 / "deploy" / "rollout" / "canary.json", "canary.json"),
                     (L151 / "deploy" / "flags.json", "flags.json"), (L151 / "docs" / "slo" / "slos.json", "slos.json")):
        pairs.append((src, LAB / "vendor" / "config" / dst))
    for src, dst in pairs:
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(src.read_bytes().replace(b"\r\n", b"\n"))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=LAB / "data")
    args = ap.parse_args(argv)
    if args.out == LAB / "data" and L151.is_dir():
        vendor()
    if args.out.exists():
        shutil.rmtree(args.out)
    args.out.mkdir(parents=True)
    for s in TRAFFIC:
        write(args.out, f"traffic/{s['id']}.json", {**s, "generated": LABEL, "start": "2027-05-04T10:00:00Z",
                                                    "max_minutes": 180, "manual_rollback_minutes": 15,
                                                    "manual_rollback_note": "assumed for the all-at-once "
                                                    "comparison: from detection to the old version serving"})
    for s in AI:
        write(args.out, f"ai/{s['id']}.json", {**s, "generated": LABEL, "start": "2027-05-04T08:00:00Z"})
    write(args.out, "manifest.json", {"generated": LABEL, "traffic": [s["id"] for s in TRAFFIC],
                                      "ai": [s["id"] for s in AI]})
    return 0


if __name__ == "__main__":
    sys.exit(main())
