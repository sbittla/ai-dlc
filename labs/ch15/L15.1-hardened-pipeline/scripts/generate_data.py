def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=LAB / "data")
    args = ap.parse_args(argv)
    out = args.out
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    write(out, "trust-root.json", {"generated": LABEL, "hmac_key": KEY, "log_key": LOG_KEY, "issuer": ISSUER,
                                   "note": "STAND-IN for Sigstore: an HMAC with a published key. Not a secret."})
    adversarial_catalogue(out)
    deployments(out)
    # The coverage reports are computed, on ../relay-repo, from the catalogue just written.
    import pipeline
    pipeline.DATA = out
    from pipeline import adversarial
    adversarial.DATA = out
    matrices = {d: adversarial.matrix_as_of("4.29.0", d) for d in ("2027-03-22", "2027-03-30", "2027-04-27")}
    train(out, matrices, adversarial.gate)
    cov_ok = coverage_report("4.29.0", adversarial.matrix_as_of("4.29.0", "2027-05-04"), adversarial.gate)
    bridge = {**adversarial.sandbox_tool().load_policy(), "network": "bridge"}
    weakened = adversarial.matrix_as_of("4.29.0", "2027-05-04", overrides={
        "test_sandbox": lambda cls: adversarial.probe_test_sandbox(cls, bridge)})
    candidates(out, cov_ok, coverage_report("4.29.0", weakened, adversarial.gate))
    incident(out)
    prs(out)
    write(out, "drafts/agent-draft-v1.yml", DRAFT_V1)
    write(out, "drafts/agent-draft-v2.yml", DRAFT_V2)
    write(out, "manifest.json", {"generated": LABEL, "candidates": 12, "train_releases": 31,
                                 "deployment_records": len(DEPLOYMENTS)})
    return 0


if __name__ == "__main__":
    sys.exit(main())
