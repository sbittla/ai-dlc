def train(out: Path, matrices: dict, gate) -> None:
    day, end = date(2027, 3, 22), date(2027, 4, 30)
    n = k = 0
    while day <= end:
        if day.weekday() < 5:
            iso = day.isoformat()
            k += 1
            version = f"4.28.{k}"  # production's train releases between 4.28.0 and 4.29.0
            key = max(k for k in matrices if k <= iso)
            cov = coverage_report(version, matrices[key], gate)
            c = candidate(f"T-{iso}", version, f"The 15:00 UTC train release of {iso}", cov,
                          eval=eval_report(labelled=iso >= "2027-03-30"))
            if iso == "2027-04-13":
                c["scans"]["trivy"] = sarif("Trivy", [finding("LAB-ADV-2027-0042", 7.5, "simulated advisory in "
                                                              "an OS package of the base image")])
            finalize(c, when=iso)
            c["train"] = {"shipped": True, "time": f"{iso}T15:00:00Z"}
            write(out, f"train/{c['id']}.json", c)
            n += 1
            if iso == "2027-04-14":
                hot = candidate(f"T-{iso}-hotfix", f"4.28.{k}-hotfix", "Hotfix built on a laptop and deployed by "
                                "hand at 18:40 UTC, 'just this once'", dict(cov, release=f"4.28.{k}-hotfix"),
                                eval=eval_report(labelled=True))
                hot["bundles"] = {}
                hot["train"] = {"shipped": True, "time": f"{iso}T18:40:00Z"}
                write(out, f"train/{hot['id']}.json", hot)
                n += 1
        day += timedelta(days=1)


