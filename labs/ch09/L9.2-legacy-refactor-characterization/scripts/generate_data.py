"""Write Lab 9.2's GENERATED data (deterministic; byte-identical on every platform).

    python scripts/generate_data.py

- data/relay-notify/: Relay 4.22.0's notification package and its tests, copied from Lab 9.1's reference
  (src/relay/__init__.py, src/relay/notify/, tests/notify/). Its frozen legacy module and corpus are the
  oracle, and the package is what integrating the five worktrees must reproduce.
- data/prod-like.json: SYNTHETIC rows shaped like production's notification_prefs table on 8 December 2026,
  and the notification events of the 18 hours the incident's migration was live. No real person's data.

The other files in data/ are inputs, written by hand: tasks.json, accepted-differences.json, agent-pr/ and
worktrees/ (the simulated agents' outputs).
"""

from __future__ import annotations

import json
import random
import shutil
from datetime import date, datetime, timedelta
from pathlib import Path

LAB = Path(__file__).resolve().parent.parent
RELAY = LAB.parent / "L9.1-spec-to-reviewed-pr" / "solution" / "relay-repo"
OUT = LAB / "data" / "relay-notify"
SEED = 2291
USERS = 1500
EVENTS = 6000
TYPES = ("mention", "assignment", "comment", "due_soon", "digest")
EVENT_TYPES = (("comment", 35), ("mention", 25), ("assignment", 15), ("due_soon", 15), ("digest", 5),
               ("security", 5))
LIVE_FROM = datetime(2026, 12, 8, 15, 4)  # the migration ran with the 15:00 UTC deploy train
LIVE_UNTIL = datetime(2026, 12, 9, 9, 10)  # the restore from backup finished


def copy_relay() -> int:
    if OUT.exists():
        shutil.rmtree(OUT)
    files = [RELAY / "src" / "relay" / "__init__.py"]
    files += sorted((RELAY / "src" / "relay" / "notify").glob("*.py"))
    files += sorted((RELAY / "tests" / "notify").glob("*.py"))
    for src in files:
        dst = OUT / src.relative_to(RELAY)
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(src.read_bytes())
    return len(files)


def prod_rows(rng: random.Random) -> list[list]:
    """Users 1 to 620 joined under Relay 3.0 to 3.3 and many kept their ';' lists; later users have ','."""
    rows = []
    for uid in range(1, USERS + 1):
        if rng.random() > 0.55:
            continue  # never changed a preference: no row
        early = uid <= 620
        muted = None
        if rng.random() < 0.88:
            names = rng.sample(TYPES + ("all",) if rng.random() < 0.05 else TYPES, rng.randint(1, 3))
            sep = ";" if early and rng.random() < 0.7 else ","
            muted = sep.join(n.title() if early and rng.random() < 0.2 else n for n in names)
        spam = None
        if rng.random() < 0.07:
            spam = (date(2026, 11, 9) + timedelta(days=rng.randint(0, 29))).isoformat()
            if rng.random() < 0.5:
                muted = None if rng.random() < 0.7 else ""
        rows.append([uid, muted, spam])
    return rows


def events(rng: random.Random) -> list[list]:
    names = [n for n, w in EVENT_TYPES for _ in range(w)]
    span = int((LIVE_UNTIL - LIVE_FROM).total_seconds())
    out = [[rng.randint(1, USERS), rng.choice(names),
            (LIVE_FROM + timedelta(seconds=rng.randint(0, span))).isoformat()] for _ in range(EVENTS)]
    return sorted(out, key=lambda e: (e[2], e[0], e[1]))


def main() -> None:
    copied = copy_relay()
    rng = random.Random(SEED)
    data = {"about": "SYNTHETIC. Shaped like production's notification_prefs table on 2026-12-08 and the events of "
                     "the hours the incident's migration was live. Generated by scripts/generate_data.py (seed "
                     f"{SEED}); no real person's data.",
            "live_from": LIVE_FROM.isoformat(), "live_until": LIVE_UNTIL.isoformat(),
            "rows": prod_rows(rng), "events": events(rng)}
    (LAB / "data" / "prod-like.json").write_text(json.dumps(data, separators=(",", ":")) + "\n", encoding="utf-8",
                                                 newline="\n")
    print(f"copied {copied} files to data/relay-notify; wrote data/prod-like.json "
          f"({len(data['rows'])} rows, {len(data['events'])} events)")


if __name__ == "__main__":
    main()
