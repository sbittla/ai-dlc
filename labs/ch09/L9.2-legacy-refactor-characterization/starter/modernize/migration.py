"""Replay a migration on production-shaped data, and count what it lost (Lab 9.2, the opening incident).

`data/prod-like.json` holds legacy rows shaped like production's (synthetic,
generated by scripts/generate_data.py) and a day of notification events.
Each migration runs on its own in-memory copy. Preferences are compared
before and after, user by user, as the legacy code would read them; then the
events are replayed through the old and the new decision.

An opt-out is one (user, type) pair the legacy code would read as muted. A
spam mark is one user with a mark. "Sent against a preference" counts events
the legacy code would have suppressed and the new code sends.
"""

