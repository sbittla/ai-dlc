def replay(events: list[list], old_send, new_send) -> tuple[int, int]:
    """(events sent against a preference, events withheld that the legacy code would send)."""
    against = withheld = 0
    for uid, ntype, at in events:
        now = datetime.fromisoformat(at)
        old, new = old_send(uid, ntype, now), new_send(uid, ntype, now)
        against += (not old) and new
        withheld += old and not new
    return against, withheld
