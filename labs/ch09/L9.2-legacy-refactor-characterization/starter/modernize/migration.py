def load_prod(data: Path) -> dict:
    return json.loads((data / "prod-like.json").read_text(encoding="utf-8"))


def legacy_db(rows: list[list]) -> sqlite3.Connection:
    conn = sqlite3.connect(":memory:", isolation_level=None)
    conn.execute("CREATE TABLE notification_prefs (user_id INTEGER PRIMARY KEY, muted_types TEXT, spam_marked_on TEXT)")
    conn.executemany("INSERT INTO notification_prefs VALUES (?, ?, ?)", [tuple(r) for r in rows])
    return conn


def before_prefs(rows: list[list], parse_muted) -> dict[int, tuple[frozenset, str | None]]:
    """What the legacy code reads for each user: (muted types, spam mark date or None)."""
    return {uid: (parse_muted(muted), spam or None) for uid, muted, spam in rows}


def after_prefs(conn: sqlite3.Connection, users) -> dict[int, tuple[frozenset, str | None]]:
    """What the new tables hold for each user."""
    out = {}
    for uid in users:
        muted = frozenset(r[0] for r in conn.execute("SELECT type FROM notify_optouts WHERE user_id = ?", (uid,)))
        row = conn.execute("SELECT marked_on FROM notify_spam_marks WHERE user_id = ?", (uid,)).fetchone()
        out[uid] = (muted, row[0] if row else None)
    return out


def table_exists(conn: sqlite3.Connection, name: str) -> bool:
    return conn.execute("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?", (name,)).fetchone() is not None


